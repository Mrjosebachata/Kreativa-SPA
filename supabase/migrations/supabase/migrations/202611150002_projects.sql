grant select on table public.project_images to anon, authenticated;
grant select on table public.project_links to anon, authenticated;
grant select on table public.project_collaborators to anon, authenticated;

grant insert, update, delete on table public.projects to authenticated;
grant insert, update, delete on table public.project_images to authenticated;
grant insert, update, delete on table public.project_links to authenticated;
grant insert, update, delete on table public.project_collaborators to authenticated;

