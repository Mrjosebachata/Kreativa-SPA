begin;

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  freelancer_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 2 and 120),
  description text not null default '' check (char_length(description) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_images (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  image_url text not null,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint project_images_order_check check (display_order >= 0),
  constraint project_images_project_order_unique unique (project_id, display_order)
);

create table if not exists public.project_links (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  label text not null check (char_length(trim(label)) between 1 and 80),
  url text not null check (char_length(trim(url)) <= 500),
  display_order integer not null default 0,
  constraint project_links_order_check check (display_order >= 0),
  constraint project_links_project_order_unique unique (project_id, display_order)
);

create table if not exists public.project_collaborators (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 2 and 100),
  display_order integer not null default 0,
  constraint project_collaborators_order_check check (display_order >= 0),
  constraint project_collaborators_project_order_unique unique (project_id, display_order)
);

create index if not exists projects_freelancer_id_idx
  on public.projects (freelancer_id, updated_at desc);

create index if not exists project_images_project_id_idx
  on public.project_images (project_id, display_order);

create index if not exists project_links_project_id_idx
  on public.project_links (project_id, display_order);

create index if not exists project_collaborators_project_id_idx
  on public.project_collaborators (project_id, display_order);

create or replace function public.set_project_updated_at()
returns trigger
language plpgsql
as $function$
begin
  new.updated_at = now();
  return new;
end;
$function$;

drop trigger if exists projects_updated_at on public.projects;

create trigger projects_updated_at
before update on public.projects
for each row execute function public.set_project_updated_at();

alter table public.projects enable row level security;
alter table public.project_images enable row level security;
alter table public.project_links enable row level security;
alter table public.project_collaborators enable row level security;

