begin;

create table if not exists public.reminders (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null references public.profiles(id) on delete cascade,
  commission_id bigint references public.commissions(id) on delete set null,
  title         text not null,
  notes         text,
  due_at        timestamptz,
  status        text not null default 'pending',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint reminders_title_check
    check (char_length(trim(title)) between 1 and 120),
  constraint reminders_notes_check
    check (notes is null or char_length(notes) <= 500),
  constraint reminders_status_check
    check (status in ('pending', 'done', 'dismissed'))
);

create index if not exists reminders_user_status_due_idx
  on public.reminders(user_id, status, due_at);

alter table public.reminders enable row level security;

revoke all on table public.reminders from anon;
revoke all on table public.reminders from authenticated;
grant select, insert, update, delete on table public.reminders to authenticated;
grant usage, select on sequence public.reminders_id_seq to authenticated;

drop policy if exists "El dueno consulta sus recordatorios" on public.reminders;
drop policy if exists "El dueno crea recordatorios validos" on public.reminders;
drop policy if exists "El dueno actualiza sus recordatorios" on public.reminders;
drop policy if exists "El dueno elimina sus recordatorios" on public.reminders;

create policy "El dueno consulta sus recordatorios"
  on public.reminders
  for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "El dueno crea recordatorios validos"
  on public.reminders
  for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and (
      commission_id is null
      or exists (
        select 1
        from public.commissions as commission
        where commission.id = reminders.commission_id
          and commission.freelancer_id = (select auth.uid())
      )
    )
  );

create policy "El dueno actualiza sus recordatorios"
  on public.reminders
  for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (
    user_id = (select auth.uid())
    and (
      commission_id is null
      or exists (
        select 1
        from public.commissions as commission
        where commission.id = reminders.commission_id
          and commission.freelancer_id = (select auth.uid())
      )
    )
  );

create policy "El dueno elimina sus recordatorios"
  on public.reminders
  for delete
  to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.set_reminders_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  new.updated_at := now();
  return new;
end;
$function$;

drop trigger if exists before_reminder_update_set_timestamp on public.reminders;
create trigger before_reminder_update_set_timestamp
  before update on public.reminders
  for each row execute function public.set_reminders_updated_at();

revoke all on function public.set_reminders_updated_at() from public;

-- Cuando exista el modulo de tickets (RF4.1), su relacion con recordatorios
-- se agregara en una migracion nueva. No se asume ninguna tabla de tickets aqui.

notify pgrst, 'reload schema';

commit;
